BEGIN
    -- Видаляємо користувачів (якщо вони існують)
    FOR u IN (SELECT username FROM all_users WHERE username IN ('C##ADMIN_SYSTEM')) LOOP
        EXECUTE IMMEDIATE 'DROP USER ' || u.username || ' CASCADE';
    END LOOP;

    -- Видаляємо ролі (якщо вони існують)
    FOR r IN (SELECT role FROM dba_roles WHERE role IN ('C##ADMIN_SYSTEM')) LOOP
        EXECUTE IMMEDIATE 'DROP ROLE ' || r.role;
    END LOOP;
EXCEPTION
    WHEN OTHERS THEN NULL; -- Ігноруємо помилки, якщо видаляти нічого
END;