--список учнів із зазначенням їхнього класу та класного керівника
SELECT
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS Student,
    CLASS.CLASSNAME,
    TEACHER.LASTNAME || ' ' || TEACHER.FIRSTNAME AS Teacher
FROM STUDENT
JOIN CLASS ON STUDENT.CLASSID = CLASS.CLASSID
JOIN TEACHER ON CLASS.TEACHERID = TEACHER.TEACHERID
ORDER BY CLASS.CLASSNAME, Student;

--контактні дані батьків та імена і день народження їхніх дітей
SELECT
    PARENT.LASTNAME || ' ' || PARENT.FIRSTNAME AS Parent,
    PARENT.PHONENUMBER,
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS Student,
    STUDENT.DATEOFBIRTH
FROM PARENT
JOIN PARENTSTUDENT ON PARENT.PARENTID = PARENTSTUDENT.PARENTID
JOIN STUDENT ON PARENTSTUDENT.STUDENTID = STUDENT.STUDENTID;

--які предмети може викладати кожен вчитель (кваліфікація)
SELECT
    TEACHER.LASTNAME || ' ' || TEACHER.FIRSTNAME || ' ' || TEACHER.PATRONYMIC AS Teacher,
    TEACHER.POSITION,
    SUBJECTNAME
FROM TEACHER
JOIN TEACHERSUBJECT ON TEACHER.TEACHERID = TEACHERSUBJECT.TEACHERID
JOIN SUBJECT ON TEACHERSUBJECT.SUBJECTID = SUBJECT.SUBJECTID
ORDER BY Teacher;

--список зауважень для учнів із прізвищами вчителів, хто їх написав
SELECT
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS Student,
    REMARKTEXT,
    TEACHER.LASTNAME || ' ' || TEACHER.FIRSTNAME || ' ' || TEACHER.PATRONYMIC AS Teacher
FROM STUDENT
JOIN REMARK ON STUDENT.STUDENTID = REMARK.STUDENTID
JOIN TEACHER ON REMARK.TEACHERID = TEACHER.TEACHERID
ORDER BY Student;

--повний розклад уроків для конкретного класу (наприклад, '11-A') з назвами предметів
SELECT
    CLASS.CLASSNAME,
    SCHEDULE.DAYOFWEEK,
    BELLSCHEDULE.LESSONNUMBER,
    BELLSCHEDULE.STARTTIME,
    SUBJECT.SUBJECTNAME,
    TEACHER.LASTNAME || ' ' || TEACHER.FIRSTNAME || ' ' || TEACHER.PATRONYMIC AS Teacher
FROM SCHEDULE
JOIN CLASS ON SCHEDULE.CLASSID = CLASS.CLASSID
JOIN SUBJECT ON SCHEDULE.SUBJECTID = SUBJECT.SUBJECTID
JOIN BELLSCHEDULE ON SCHEDULE.CALLID = BELLSCHEDULE.CALLID
JOIN TEACHER ON SCHEDULE.TEACHERID = TEACHER.TEACHERID
WHERE CLASS.CLASSNAME = '11-А'
ORDER BY SCHEDULE.DAYOFWEEK, BELLSCHEDULE.LESSONNUMBER;

--завантаженість аудиторій: який предмет у якій аудиторії викладається
SELECT
    CLASSROOM.ROOMNUMBER,
    CLASSROOM.TYPE,
    SUBJECT.SUBJECTNAME,
    SCHEDULE.DAYOFWEEK,
    BELLSCHEDULE.LESSONNUMBER
FROM SCHEDULE
JOIN CLASSROOM ON SCHEDULE.ROOMID = CLASSROOM.ROOMID
JOIN SUBJECT ON SCHEDULE.SUBJECTID = SUBJECT.SUBJECTID
JOIN BELLSCHEDULE ON SCHEDULE.CALLID = BELLSCHEDULE.CALLID
ORDER BY CLASSROOM.ROOMNUMBER, SCHEDULE.DAYOFWEEK, LESSONNUMBER;

--журнал проведених уроків: тема уроку, дата і предмет
SELECT
    LESSON.LESSONDATE,
    SUBJECT.SUBJECTNAME,
    LESSON.TOPIC,
    CLASS.CLASSNAME
FROM LESSON
JOIN SCHEDULE ON LESSON.SCHEDULEID = SCHEDULE.SCHEDULEID
JOIN SUBJECT ON SCHEDULE.SUBJECTID = SUBJECT.SUBJECTID
JOIN CLASS ON SCHEDULE.CLASSID = CLASS.CLASSID;

--архiв домашніх завдань: список усіх уроків, де було задано домашнє завдання (окрім пустих), відсортований від нових до старих
SELECT
    CLASS.CLASSNAME,
    LESSON.LESSONDATE,
    LESSON.TOPIC,
    LESSON.HOMEWORKDESCRIPTION
FROM LESSON
JOIN SCHOOL_DB.SCHEDULE ON LESSON.SCHEDULEID = SCHEDULE.SCHEDULEID
JOIN CLASS ON SCHEDULE.CLASSID = CLASS.CLASSID
WHERE LESSON.HOMEWORKDESCRIPTION IS NOT NULL
ORDER BY LESSON.LESSONDATE DESC;

--середній бал кожного учня по всіх предмета
SELECT
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS Student,
    ROUND(AVG(GRADE.GRADEVALUE), 2) AS AverageScore
FROM STUDENT
JOIN SCHOOL_DB.GRADE ON STUDENT.STUDENTID = GRADE.STUDENTID
GROUP BY STUDENT.LASTNAME, STUDENT.FIRSTNAME
ORDER BY AverageScore DESC;

--кількість пропусків у кожного учня
SELECT
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS Student,
    COUNT(ATTENDANCE.ATTENDANCEID) AS TotalAbsences
FROM STUDENT
JOIN ATTENDANCE ON STUDENT.STUDENTID = ATTENDANCE.STUDENTID
WHERE ATTENDANCE.ISPRESENT = 0
GROUP BY STUDENT.LASTNAME, STUDENT.FIRSTNAME;

--кількість учнів у кожному класі
SELECT
    CLASS.CLASSNAME,
    COUNT(STUDENT.STUDENTID) AS StudentCount
FROM CLASS
JOIN STUDENT ON CLASS.CLASSID = STUDENT.CLASSID
GROUP BY CLASS.CLASSNAME;

--детальний звіт про оцінки: хто, за який предмет і яку оцінку отримав
SELECT
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS Student,
    SUBJECT.SUBJECTNAME,
    GRADE.GRADEVALUE,
    GRADE.GRADEDATE
FROM GRADE
JOIN STUDENT ON GRADE.STUDENTID = STUDENT.STUDENTID
JOIN LESSON ON GRADE.LESSONID = LESSON.LESSONID
JOIN SCHOOL_DB.SCHEDULE ON LESSON.SCHEDULEID = SCHEDULE.SCHEDULEID
JOIN SUBJECT ON SCHEDULE.SUBJECTID = SUBJECT.SUBJECTID;

--кількість годин за навчальною програмою для кожного предмета (сумарно по всіх рівнях)
SELECT
    SUBJECT.SUBJECTNAME,
    SUM(CURRICULUM.HOURS) AS TotalHours
FROM CURRICULUM
JOIN SUBJECT ON CURRICULUM.SUBJECTID = SUBJECT.SUBJECTID
GROUP BY SUBJECT.SUBJECTNAME;

--список учнів, які отримали оцінки "10", "11" або "12" (відмінники) за грудень 2024
SELECT DISTINCT
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS Student,
    GRADE.GRADEVALUE,
    GRADE.GRADEDATE
FROM STUDENT
JOIN GRADE ON STUDENT.STUDENTID = GRADE.STUDENTID
WHERE GRADE.GRADEVALUE >= 10
  AND GRADE.GRADEDATE >= ADD_MONTHS(SYSDATE, -13);

--класи, в яких проводяться уроки у вчителів з посадою "Вчитель початкових класів"
SELECT DISTINCT
    CLASSROOM.ROOMNUMBER,
    TEACHER.LASTNAME || ' ' || TEACHER.FIRSTNAME AS Teacher
FROM SCHEDULE
JOIN CLASSROOM ON SCHEDULE.ROOMID = CLASSROOM.ROOMID
JOIN TEACHER ON SCHEDULE.TEACHERID = TEACHER.TEACHERID
WHERE TEACHER.POSITION LIKE '%початкових класів%';

--які теми відповідають якому предмету для 11-го класу
SELECT
    SUBJECT.SUBJECTNAME,
    CURRICULUM.TOPICNAME,
    CURRICULUM.HOURS
FROM CURRICULUM
JOIN SUBJECT ON CURRICULUM.SUBJECTID = SUBJECT.SUBJECTID
WHERE CURRICULUM.CLASSLEVEL = 11;

--знайти учнів, які мають середній бал вище, ніж середній бал по всій школі
SELECT
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS Student,
    ROUND(AVG(GRADE.GRADEVALUE), 2) AS StudentAvg
FROM STUDENT
JOIN GRADE ON STUDENT.STUDENTID = GRADE.STUDENTID
GROUP BY STUDENT.LASTNAME, STUDENT.FIRSTNAME
HAVING ROUND(AVG(GRADE.GRADEVALUE), 2) > (
    SELECT ROUND(AVG(GRADE.GRADEVALUE), 2)
    FROM GRADE
);

--знайти вчителів, у яких немає жодного уроку в розкладі (наприклад, нові вчителі або ті, хто у відпустці)
SELECT
    TEACHER.LASTNAME || ' ' || TEACHER.FIRSTNAME AS Teacher,
    TEACHER.POSITION
FROM TEACHER
WHERE TEACHER.TEACHERID NOT IN (
    SELECT DISTINCT TEACHERID
    FROM Schedule
);

--знайти предмети, з яких ще не було виставлено жодної оцінки
SELECT
    SUBJECT.SUBJECTNAME
FROM SUBJECT
WHERE SUBJECT.SUBJECTID NOT IN (
    SELECT DISTINCT SCHEDULE.SUBJECTID
    FROM SCHEDULE
    JOIN LESSON ON SCHEDULE.SCHEDULEID = LESSON.SCHEDULEID
    JOIN GRADE ON LESSON.LESSONID = GRADE.LESSONID
);

--список класів, де кількість учнів менша за середню місткість аудиторій
SELECT
    CLASS.CLASSNAME,
    COUNT(STUDENT.STUDENTID) AS StudentCount
FROM CLASS
JOIN STUDENT ON CLASS.CLASSID = STUDENT.CLASSID
GROUP BY CLASS.CLASSNAME
HAVING COUNT(STUDENT.STUDENTID) < (
    SELECT AVG(CAPACITY)
    FROM CLASSROOM
);