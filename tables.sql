CREATE TABLE Classroom (
    RoomID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    RoomNumber VARCHAR2(10) NOT NULL,
    Capacity NUMBER(3),
    Type VARCHAR2(50)
);

CREATE TABLE Semester (
    SemesterID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SemesterName VARCHAR2(50) NOT NULL,
    StartDate DATE NOT NULL,
    EndDate DATE NOT NULL,
    CONSTRAINT CHK_Semester_Dates
        CHECK ( EndDate > StartDate )
);

CREATE TABLE BellSchedule (
    CallID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    LessonNumber NUMBER(1) NOT NULL
        CHECK ( LessonNumber BETWEEN 1 AND 12),
    StartTime VARCHAR2(5) NOT NULL,
    EndTime VARCHAR2(5) NOT NULL,
    Shift NUMBER(1) DEFAULT 1
        CHECK ( Shift IN (1, 2) ),

    CONSTRAINT CHK_StartTime_Format
        CHECK ( REGEXP_LIKE(StartTime, '^([0-1][0-9]|2[0-3]):[0-5][0-9]$') ),
    CONSTRAINT CHK_EndTime_Format
        CHECK ( REGEXP_LIKE(EndTime, '^([0-1][0-9]|2[0-3]):[0-5][0-9]$') )
);

CREATE TABLE Subject (
    SubjectID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SubjectName VARCHAR2(100) NOT NULL
);

CREATE TABLE Teacher (
    TeacherID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    LastName VARCHAR2(50) NOT NULL,
    FirstName VARCHAR2(50) NOT NULL,
    Patronymic VARCHAR2(50),
    Position VARCHAR2(100) NOT NULL,
    Email VARCHAR2(100) NOT NULL UNIQUE,
    PhoneNumber VARCHAR2(20) UNIQUE
);

CREATE TABLE Parent (
    ParentID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    LastName VARCHAR2(50) NOT NULL,
    FirstName VARCHAR2(50) NOT NULL,
    Patronymic VARCHAR2(50),
    Email VARCHAR2(100) UNIQUE,
    PhoneNumber VARCHAR2(20) UNIQUE
);

CREATE TABLE Class (
    ClassID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ClassName VARCHAR2(10) NOT NULL,
    AcademicYear VARCHAR2(15) NOT NULL,

    TeacherID NUMBER NOT NULL,

    CONSTRAINT FK_Class_Teacher
        FOREIGN KEY (TeacherID)
            REFERENCES Teacher(TeacherID)
);

CREATE TABLE Student (
    StudentID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    LastName VARCHAR2(50) NOT NULL,
    FirstName VARCHAR2(50) NOT NULL,
    Patronymic VARCHAR2(50),
    DateOfBirth DATE NOT NULL,
    Email VARCHAR2(100) UNIQUE,
    PhoneNumber VARCHAR2(20) UNIQUE,

    ClassID NUMBER NOT NULL,

    CONSTRAINT FK_Student_Class
        FOREIGN KEY (ClassID)
            REFERENCES Class(ClassID)
);

CREATE TABLE Curriculum (
    CurriculumID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ClassLevel NUMBER(2) NOT NULL
        CHECK ( ClassLevel BETWEEN 1 AND 12),
    TopicName VARCHAR2(500) NOT NULL,
    Hours NUMBER(3) DEFAULT 1,

    SubjectID NUMBER NOT NULL,

    CONSTRAINT FK_Curriculum_Subject
        FOREIGN KEY (SubjectID)
            REFERENCES Subject(SubjectID)
);

CREATE TABLE Schedule (
    ScheduleID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DayOfWeek NUMBER(1) NOT NULL
        CHECK ( DayOfWeek BETWEEN 1 AND 7),

    ClassID NUMBER NOT NULL,
    SubjectID NUMBER NOT NULL,
    TeacherID NUMBER NOT NULL,
    RoomID NUMBER NOT NULL,
    CallID NUMBER NOT NULL,
    SemesterID NUMBER NOT NULL,

    CONSTRAINT FK_Schedule_Class
        FOREIGN KEY (ClassID)
            REFERENCES Class(ClassID),

    CONSTRAINT FK_Schedule_Subject
        FOREIGN KEY (SubjectID)
            REFERENCES Subject(SubjectID),

    CONSTRAINT FK_Schedule_Teacher
        FOREIGN KEY (TeacherID)
            REFERENCES Teacher(TeacherID),

    CONSTRAINT FK_Schedule_Room
        FOREIGN KEY (RoomID)
            REFERENCES Classroom(RoomID),

    CONSTRAINT FK_Schedule_Call
        FOREIGN KEY (CallID)
            REFERENCES BellSchedule(CallID),

    CONSTRAINT FK_Schedule_Semester
        FOREIGN KEY (SemesterID)
            REFERENCES Semester(SemesterID)
);

CREATE TABLE Lesson (
    LessonID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    LessonDate DATE NOT NULL,
    Topic VARCHAR2(500) NOT NULL,
    HomeworkDescription VARCHAR2(1000),
    HomeworkDeadline DATE,
    AttachmentURL VARCHAR2(1000),

    ScheduleID NUMBER NOT NULL,

    CONSTRAINT FK_Lesson_Schedule FOREIGN KEY (ScheduleID) REFERENCES Schedule(ScheduleID)
);

CREATE TABLE Grade (
    GradeID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    GradeValue NUMBER(2) NOT NULL CHECK ( GradeValue BETWEEN 1 AND 12),
    GradeDate DATE DEFAULT SYSDATE,
    GradeComment VARCHAR2(200),

    StudentID NUMBER NOT NULL,
    LessonID NUMBER NOT NULL,

    CONSTRAINT FK_Grade_Student FOREIGN KEY (StudentID) REFERENCES Student(StudentID),
    CONSTRAINT FK_Grade_Lesson FOREIGN KEY (LessonID) REFERENCES Lesson(LessonID)
);

CREATE TABLE Attendance (
    AttendanceID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    IsPresent NUMBER(1) DEFAULT 1 NOT NULL CHECK ( IsPresent IN (0, 1) ),
    Reason VARCHAR2(100),

    StudentID NUMBER NOT NULL,
    LessonID NUMBER NOT NULL,

    CONSTRAINT FK_Attendance_Student FOREIGN KEY (StudentID) REFERENCES Student(StudentID),
    CONSTRAINT FK_Attendance_Lesson FOREIGN KEY (LessonID) REFERENCES Lesson(LessonID)
);

CREATE TABLE Remark (
    RemarkID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    RemarkDate DATE DEFAULT SYSDATE,
    RemarkText VARCHAR2(500) NOT NULL,

    StudentID NUMBER NOT NULL,
    TeacherID NUMBER NOT NULL,

    CONSTRAINT FK_Remark_Student FOREIGN KEY (StudentID) REFERENCES Student(StudentID),
    CONSTRAINT FK_Remark_Teacher FOREIGN KEY (TeacherID) REFERENCES Teacher(TeacherID)
);

CREATE TABLE ParentStudent (
    ParentID NUMBER NOT NULL,
    StudentID NUMBER NOT NULL,

    CONSTRAINT PK_ParentStudent PRIMARY KEY (ParentID, StudentID),
    CONSTRAINT FK_ParentStudent_Parent FOREIGN KEY (ParentID) REFERENCES Parent(ParentID),
    CONSTRAINT FK_ParentStudent_Student FOREIGN KEY (StudentID) REFERENCES Student(StudentID)
);

CREATE TABLE TeacherSubject (
    TeacherID NUMBER NOT NULL,
    SubjectID NUMBER NOT NULL,

    CONSTRAINT PK_TeacherSubject PRIMARY KEY (TeacherID, SubjectID),
    CONSTRAINT FK_TeacherSubject_Teacher FOREIGN KEY (TeacherID) REFERENCES Teacher(TeacherID),
    CONSTRAINT FK_TeacherSubject_Subject FOREIGN KEY (SubjectID) REFERENCES Subject(SubjectID)
);