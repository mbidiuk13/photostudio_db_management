--форматування даних (перша буква імені та прізвища велика, а email переводиться у нижній регістр)
CREATE OR REPLACE TRIGGER TRG_Student_Format
BEFORE INSERT OR UPDATE ON STUDENT
FOR EACH ROW
BEGIN
    -- Робимо першу букву великою, решту маленькими
    :NEW.FirstName := INITCAP(:NEW.FirstName);
    :NEW.LastName  := INITCAP(:NEW.LastName);

    -- Email завжди з маленької літери
    :NEW.Email := LOWER(:NEW.Email);
END;

BEGIN
    -- Вводимо дані "криво": малі букви в імені, великі в пошті
    INSERT INTO STUDENT (LASTNAME, FIRSTNAME, DATEOFBIRTH, EMAIL, CLASSID)
    VALUES ('шевченко', 'тарас', TO_DATE('2010-03-09', 'YYYY-MM-DD'), 'TARAS.SHEV@GMAIL.COM', 1);
    COMMIT;
END;

-- Перевіряємо результат: має бути 'Шевченко', 'Тарас' та 'taras.shev@gmail.com'
SELECT LASTNAME, FIRSTNAME, EMAIL
FROM STUDENT
WHERE LASTNAME = 'Шевченко';

--хто змінив оцінку і якою вона була раніше
CREATE TABLE GradeHistory (
    HistoryID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    GradeID NUMBER,
    OldValue NUMBER,
    NewValue NUMBER,
    ChangeDate DATE DEFAULT SYSDATE,
    ChangedBy VARCHAR2(100)
);

CREATE OR REPLACE TRIGGER TRG_Grade_Audit
AFTER UPDATE OF GRADEVALUE ON GRADE
FOR EACH ROW
BEGIN
    -- Записуємо, якщо оцінка змінилася
    IF :OLD.GradeValue != :NEW.GradeValue THEN
        INSERT INTO GradeHistory (GradeID, OldValue, NewValue, ChangedBy)
        VALUES (:NEW.GradeID, :OLD.GradeValue, :NEW.GradeValue, USER);
    END IF;
END;

BEGIN
    -- 1. Спочатку додамо оцінку
    INSERT INTO GRADE (GRADEVALUE, STUDENTID, LESSONID) VALUES (8, 1, 1);
    COMMIT;

    -- 2. Тепер змінимо її (наприклад, виправимо 8 на 10)
    UPDATE GRADE SET GRADEVALUE = 10
    WHERE GRADEID = (SELECT MAX(GRADEID) FROM GRADE);
    COMMIT;
END;

-- 3. Дивимось таблицю історії
SELECT * FROM GradeHistory ORDER BY HistoryID DESC;

--заборона змінювати оцінку, якщо з моменту її виставлення пройшло більше 14 днів (архівний період)
CREATE OR REPLACE TRIGGER TRG_Grade_Lock
BEFORE UPDATE ON GRADE
FOR EACH ROW
BEGIN
    -- Якщо пройшло більше 14 днів від дати виставлення
    IF (:OLD.GradeDate < SYSDATE - 14) THEN
        RAISE_APPLICATION_ERROR(-20001, 'Помилка: Не можна змінювати оцінки, старіші за 2 тижні!');
    END IF;
END;

BEGIN
    -- 1. Створимо "стару" оцінку (датуємо її минулим місяцем вручну, якщо поле дозволяє, або імітуємо ситуацію)
    -- Для тесту ми спробуємо оновити запис, уявивши, що він старий.
    -- Або створимо запис з датою -20 днів:
    INSERT INTO GRADE (GRADEVALUE, GRADEDATE, STUDENTID, LESSONID)
    VALUES (5, SYSDATE - 20, 1, 1);

    -- 2. Спробуємо її змінити
    UPDATE GRADE SET GRADEVALUE = 12
    WHERE GRADEID = (SELECT MAX(GRADEID) FROM GRADE);
END;

--збереження даних учня в архівну таблицю при видаленні
CREATE TABLE StudentArchive (
    ArchivedID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OriginalStudentID NUMBER,
    FullName VARCHAR2(150),
    DeletedDate DATE DEFAULT SYSDATE
);

CREATE OR REPLACE TRIGGER TRG_Student_Archive
BEFORE DELETE ON STUDENT
FOR EACH ROW
BEGIN
    INSERT INTO StudentArchive (OriginalStudentID, FullName)
    VALUES (:OLD.StudentID, :OLD.LastName || ' ' || :OLD.FirstName);
END;

BEGIN
    -- 1. Видаляємо учня (наприклад, того Тараса Шевченка, якого створили раніше)
    DELETE FROM STUDENT WHERE EMAIL = 'taras.shev@gmail.com';
    COMMIT;
END;

-- 2. Перевіряємо архів
SELECT * FROM StudentArchive ORDER BY ArchivedID DESC;

--перевірка дати народження
CREATE OR REPLACE TRIGGER TRG_Check_BirthDate
BEFORE INSERT OR UPDATE ON STUDENT
FOR EACH ROW
BEGIN
    -- Перевірка: Дата народження не може бути в майбутньому
    IF :NEW.DateOfBirth > SYSDATE THEN
        RAISE_APPLICATION_ERROR(-20003, 'Помилка: Дата народження не може бути в майбутньому!');
    END IF;

    -- Перевірка: Учень не може бути старшим за 20 років (для школи)
    IF :NEW.DateOfBirth < ADD_MONTHS(SYSDATE, -12*20) THEN
         RAISE_APPLICATION_ERROR(-20004, 'Помилка: Учень занадто дорослий для школи (більше 20 років)!');
    END IF;
END;

BEGIN
    -- Спробуємо додати "мандрівника в часі" (дата народження завтра)
    INSERT INTO STUDENT (LASTNAME, FIRSTNAME, DATEOFBIRTH, CLASSID)
    VALUES ('Мартин', 'Макфлай', SYSDATE + 1, 1);
END;