--готовий розклад
CREATE OR REPLACE VIEW V_PublicSchedule AS
SELECT
    CLASS.CLASSNAME,
    CASE SCHEDULE.DAYOFWEEK
        WHEN 1 THEN 'Понеділок'
        WHEN 2 THEN 'Вівторок'
        WHEN 3 THEN 'Середа'
        WHEN 4 THEN 'Четвер'
        WHEN 5 THEN 'П''ятниця'
        WHEN 6 THEN 'Субота'
        WHEN 7 THEN 'Неділя'
    END AS WeekDay,
    BELLSCHEDULE.LESSONNUMBER,
    BELLSCHEDULE.STARTTIME || ' - ' || BELLSCHEDULE.ENDTIME AS LessonTime,
    SUBJECT.SUBJECTNAME,
    TEACHER.LASTNAME || ' ' || SUBSTR(TEACHER.FIRSTNAME, 1, 1) || '.' AS TeacherName, -- Скорочуємо ім'я (Коваленко О.)
    CLASSROOM.ROOMNUMBER
FROM SCHEDULE
JOIN CLASS ON SCHEDULE.CLASSID = CLASS.CLASSID
JOIN BELLSCHEDULE ON SCHEDULE.CALLID = BELLSCHEDULE.CALLID
JOIN SUBJECT ON SCHEDULE.SUBJECTID = SUBJECT.SUBJECTID
JOIN TEACHER ON SCHEDULE.TEACHERID = TEACHER.TEACHERID
JOIN CLASSROOM ON SCHEDULE.ROOMID = CLASSROOM.ROOMID
ORDER BY CLASS.CLASSNAME, SCHEDULE.DAYOFWEEK, BELLSCHEDULE.LESSONNUMBER;

-- Дивимось розклад для конкретного класу через View
SELECT * FROM V_PublicSchedule
WHERE CLASSNAME = '11-А' -- Або введіть інший існуючий клас
ORDER BY WeekDay;

--електронний журнал (хто, за що, коли і яку оцінку отримав, а також тему уроку)
CREATE OR REPLACE VIEW V_FullGrades AS
SELECT
    STUDENT.STUDENTID,
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS StudentName,
    CLASS.CLASSNAME,
    SUBJECT.SUBJECTNAME,
    LESSON.TOPIC,
    LESSON.LESSONDATE,
    GRADE.GRADEVALUE,
    GRADE.GRADECOMMENT
FROM GRADE
JOIN STUDENT ON GRADE.STUDENTID = STUDENT.STUDENTID
JOIN CLASS ON STUDENT.CLASSID = CLASS.CLASSID
JOIN LESSON ON GRADE.LESSONID = LESSON.LESSONID
JOIN SCHEDULE ON LESSON.SCHEDULEID = SCHEDULE.SCHEDULEID
JOIN SUBJECT ON SCHEDULE.SUBJECTID = SUBJECT.SUBJECTID;

-- Отримуємо останні 10 оцінок по школі
SELECT * FROM V_FullGrades
ORDER BY LESSONDATE DESC
FETCH FIRST 10 ROWS ONLY;

--рейтинг успішності (автоматично рахує середній бал кожного учня)
CREATE OR REPLACE VIEW V_StudentRating AS
SELECT
    STUDENT.STUDENTID,
    STUDENT.LASTNAME || ' ' || STUDENT.FIRSTNAME AS StudentName,
    CLASS.CLASSNAME,
    COUNT(GRADE.GRADEID) AS TotalGrades,       -- Скільки всього оцінок отримав
    ROUND(AVG(GRADE.GRADEVALUE), 2) AS AvgScore -- Середній бал
FROM STUDENT
JOIN CLASS ON STUDENT.CLASSID = CLASS.CLASSID
LEFT JOIN GRADE ON STUDENT.STUDENTID = GRADE.STUDENTID -- LEFT JOIN, щоб показати навіть тих, у кого немає оцінок
GROUP BY STUDENT.STUDENTID, STUDENT.LASTNAME, STUDENT.FIRSTNAME, CLASS.CLASSNAME;

-- Дивимось топ учнів за середнім балом
SELECT * FROM V_StudentRating
ORDER BY AvgScore;